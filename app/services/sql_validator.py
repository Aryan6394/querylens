"""AST-level SQL safety validator for Google BigQuery."""

from __future__ import annotations

import re

import sqlglot
from sqlglot import exp
from sqlglot.errors import ParseError

from app.core.exceptions import UnsafeSQLError

# Statement root types permitted to execute
_ALLOWED_ROOT_TYPES = (exp.Select, exp.Union, exp.Intersect, exp.Except)

# Forbidden AST node names anywhere inside a query tree
_FORBIDDEN_NODE_NAMES = (
    "Insert",
    "Update",
    "Delete",
    "Drop",
    "Create",
    "Alter",
    "Merge",
    "TruncateTable",
    "Truncate",
    "Command",
    "Grant",
    "Revoke",
    "Commit",
    "Rollback",
    "Transaction",
    "Set",
    "Pragma",
    "Copy",
    "LoadData",
)

_FORBIDDEN_NODES = tuple(
    node for name in _FORBIDDEN_NODE_NAMES if (node := getattr(exp, name, None)) is not None
)

_FENCE_RE = re.compile(r"^\s*```(?:sql)?\s*(.*?)\s*```\s*$", re.IGNORECASE | re.DOTALL)


def strip_markdown_fences(raw_sql: str) -> str:
    """Remove surrounding ```sql ... ``` fences if returned by an LLM."""
    text = raw_sql.strip()
    match = _FENCE_RE.match(text)
    return match.group(1).strip() if match else text


def validate_sql(raw_sql: str, allowed_dataset: str | None = None) -> str:
    """Validate that SQL is a single, read-only BigQuery query.

    Args:
        raw_sql: SQL string generated by the LLM or user.
        allowed_dataset: Optional 'project.dataset' allowlist to restrict table access.

    Returns:
        Normalised, comment-free BigQuery SQL string.

    Raises:
        UnsafeSQLError: If SQL is empty, invalid, multi-statement, non-read-only,
            or references a dataset outside `allowed_dataset`.
    """
    cleaned = strip_markdown_fences(raw_sql)
    if not cleaned:
        raise UnsafeSQLError("SQL query is empty.")

    try:
        parsed = sqlglot.parse(cleaned, read="bigquery")
    except ParseError as exc:
        raise UnsafeSQLError(f"Invalid BigQuery SQL syntax: {exc}") from exc

    statements = [stmt for stmt in parsed if stmt is not None]
    if not statements:
        raise UnsafeSQLError("SQL query contains no executable statements.")
    if len(statements) > 1:
        raise UnsafeSQLError("Multiple SQL statements are not allowed.")

    tree = statements[0]

    if not isinstance(tree, _ALLOWED_ROOT_TYPES):
        raise UnsafeSQLError(
            f"Only read-only SELECT queries are permitted (got {type(tree).__name__})."
        )

    for node in tree.walk():
        if isinstance(node, _FORBIDDEN_NODES):
            raise UnsafeSQLError(
                f"Forbidden SQL operation detected: {type(node).__name__}."
            )
        if isinstance(node, exp.Select) and node.args.get("into"):
            raise UnsafeSQLError("SELECT INTO statements are not permitted.")

    if allowed_dataset:
        _enforce_dataset_allowlist(tree, allowed_dataset)

    return tree.sql(dialect="bigquery")


def _enforce_dataset_allowlist(tree: exp.Expression, allowed_dataset: str) -> None:
    """Ensure all referenced physical tables belong to the configured dataset."""
    expected_full = allowed_dataset.strip("` ").lower()
    expected_dataset_only = expected_full.split(".")[-1]

    cte_names = {
        cte.alias_or_name.lower()
        for cte in tree.find_all(exp.CTE)
        if cte.alias_or_name
    }

    for table in tree.find_all(exp.Table):
        if not table.name:
            continue

        catalog = (table.catalog or "").strip("` ").lower()
        db = (table.db or "").strip("` ").lower()
        name = table.name.strip("` ").lower()

        # Skip CTE aliases referenced without a dataset qualifier
        if not catalog and not db and name in cte_names:
            continue

        # Allow INFORMATION_SCHEMA queries scoped to the allowed dataset
        if catalog and db:
            qualified = f"{catalog}.{db}"
            if qualified != expected_full:
                raise UnsafeSQLError(
                    f"Access to dataset '{qualified}' is blocked; "
                    f"only '{expected_full}' is permitted."
                )
        elif db and db != expected_dataset_only:
            raise UnsafeSQLError(
                f"Access to dataset '{db}' is blocked; "
                f"only '{expected_full}' is permitted."
            )